CREATE TABLE recommendation_batches (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    reference_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    algorithm_version VARCHAR(32) NOT NULL,
    catalog_fingerprint CHAR(64) NULL,
    profile_fingerprint CHAR(64) NULL,
    selected_count SMALLINT NOT NULL DEFAULT 0,
    generated_at DATETIME(6) NULL,
    lease_token CHAR(36) NULL,
    lease_until DATETIME(6) NULL,
    attempt_count INT NOT NULL DEFAULT 0,
    automatic_attempt_count INT NOT NULL DEFAULT 0,
    failed_at DATETIME(6) NULL,
    next_attempt_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    operational_pending_since DATETIME(6) NULL,
    failure_code VARCHAR(64) NULL,
    CONSTRAINT uk_recommendation_user_date UNIQUE (user_id, reference_date),
    CONSTRAINT fk_recommendation_batch_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT ck_recommendation_batch_status CHECK (status IN ('PENDING','BUILDING','READY','FAILED')),
    CONSTRAINT ck_recommendation_selected_count CHECK (selected_count BETWEEN 0 AND 30),
    CONSTRAINT ck_recommendation_attempts CHECK (attempt_count >= 0 AND automatic_attempt_count BETWEEN 0 AND 3),
    INDEX idx_recommendation_recovery (reference_date, status, next_attempt_at, lease_until, id),
    INDEX idx_recommendation_latest_ready (user_id, status, reference_date)
);

CREATE TABLE recommendation_items (
    batch_id BIGINT NOT NULL,
    position SMALLINT NOT NULL,
    book_id BIGINT NOT NULL,
    reason_type VARCHAR(16) NOT NULL,
    reason_value TEXT NOT NULL,
    reason_text TEXT NOT NULL,
    source_book_id BIGINT NULL,
    source_book_title VARCHAR(500) NOT NULL,
    evidence_weight SMALLINT NOT NULL,
    PRIMARY KEY (batch_id, position),
    CONSTRAINT uk_recommendation_item_book UNIQUE (batch_id, book_id),
    CONSTRAINT fk_recommendation_item_batch FOREIGN KEY (batch_id) REFERENCES recommendation_batches(id) ON DELETE CASCADE,
    CONSTRAINT fk_recommendation_item_book FOREIGN KEY (book_id) REFERENCES books(id) ON DELETE CASCADE,
    CONSTRAINT fk_recommendation_item_source FOREIGN KEY (source_book_id) REFERENCES books(id) ON DELETE SET NULL,
    CONSTRAINT ck_recommendation_position CHECK (position BETWEEN 1 AND 30),
    CONSTRAINT ck_recommendation_evidence_weight CHECK (evidence_weight BETWEEN 1 AND 4),
    CONSTRAINT ck_recommendation_reason_type CHECK (reason_type IN ('SUBJECT','AUTHOR')),
    INDEX idx_recommendation_item_book (book_id),
    INDEX idx_recommendation_item_source (source_book_id)
);
